"""License keys for distributing the toolkit: Ed25519-signed tokens bound to a machine.

Owner side (keeps the private key, never ships it):
    kdp license keygen --out <folder outside the repo>      -> license_private.pem + kdp_studio/license_pub.py
    kdp license issue --to "Shop A" --machine <id> --days 365 --key <folder>/license_private.pem

Client side (the copy installed on another computer):
    kdp license machine-id            -> the id to send to the owner
    kdp license activate <token>      -> verified against the embedded public key, stored per user
    kdp license status

Enforcement is on only when `kdp_studio/license_pub.py` exists (i.e. the owner generated keys); then
every command except `license` refuses to run without a valid, unexpired token for this machine.
Set KDP_STUDIO_DEV=1 (for example in .env) on the owner's own machines to skip the check.
Honest limit: Python source can be edited, so this deters casual copying; it is not DRM.
"""

from __future__ import annotations

import base64
import datetime as dt
import hashlib
import json
import os
import platform
import uuid
from pathlib import Path


class LicenseError(RuntimeError):
    pass


def _b64e(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode().rstrip("=")


def _b64d(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def machine_id() -> str:
    """Stable per-computer id: Windows MachineGuid when available, else hostname + primary MAC."""
    parts = [platform.node()]
    try:
        import winreg  # Windows only

        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\Microsoft\Cryptography") as k:
            parts.append(str(winreg.QueryValueEx(k, "MachineGuid")[0]))
    except Exception:  # noqa: BLE001 - not Windows or no access
        parts.append(f"{uuid.getnode():012x}")
    digest = hashlib.sha256("|".join(parts).encode()).hexdigest()[:20].upper()
    return "-".join(digest[i : i + 5] for i in range(0, 20, 5))


def store_path() -> Path:
    base = os.environ.get("KDP_STUDIO_HOME") or (os.environ.get("LOCALAPPDATA") or str(Path.home() / ".local" / "share"))
    return Path(base) / "kdp-studio" / "license.json"


def public_key_b64() -> str | None:
    try:
        from . import license_pub  # generated by `kdp license keygen`
    except ImportError:
        return None
    return getattr(license_pub, "PUBLIC_KEY_B64", None)


def enforced() -> bool:
    return public_key_b64() is not None and os.environ.get("KDP_STUDIO_DEV") != "1"


# ---------------------------------------------------------------- owner
def keygen(out_dir: Path, package_dir: Path | None = None) -> tuple[Path, Path]:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    out_dir.mkdir(parents=True, exist_ok=True)
    priv = Ed25519PrivateKey.generate()
    priv_path = out_dir / "license_private.pem"
    priv_path.write_bytes(priv.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    pub_raw = priv.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    pub_path = (package_dir or Path(__file__).parent) / "license_pub.py"
    pub_path.parent.mkdir(parents=True, exist_ok=True)
    pub_path.write_text(f'"""Public key for license verification (generated by `kdp license keygen`; the private key stays with the owner)."""\n\nPUBLIC_KEY_B64 = "{_b64e(pub_raw)}"\n', encoding="utf-8")
    return priv_path, pub_path


def issue(private_key_path: Path, licensee: str, machine: str, days: int | None = 365, features: list[str] | None = None) -> str:
    from cryptography.hazmat.primitives import serialization

    priv = serialization.load_pem_private_key(private_key_path.read_bytes(), password=None)
    now = dt.datetime.now(dt.timezone.utc)
    payload = {
        "licensee": licensee,
        "machine": machine.strip().upper(),
        "issued": now.strftime("%Y-%m-%d"),
        "expires": (now + dt.timedelta(days=days)).strftime("%Y-%m-%d") if days else None,
        "features": features or ["all"],
        "v": 1,
    }
    body = json.dumps(payload, separators=(",", ":"), sort_keys=True).encode()
    sig = priv.sign(body)
    return f"{_b64e(body)}.{_b64e(sig)}"


# ---------------------------------------------------------------- client
def verify(token: str, public_b64: str | None = None, machine: str | None = None, today: dt.date | None = None) -> dict:
    """Return the payload of a valid token for this machine; raise LicenseError otherwise."""
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

    public_b64 = public_b64 or public_key_b64()
    if not public_b64:
        raise LicenseError("no public key embedded in this build")
    try:
        body_b64, sig_b64 = token.strip().split(".")
        body, sig = _b64d(body_b64), _b64d(sig_b64)
        Ed25519PublicKey.from_public_bytes(_b64d(public_b64)).verify(sig, body)
        payload = json.loads(body)
    except (ValueError, InvalidSignature, json.JSONDecodeError) as exc:
        raise LicenseError("license key is malformed or not signed by the owner") from exc
    machine = (machine or machine_id()).strip().upper()
    if payload.get("machine") not in ("*", machine):
        raise LicenseError(f"license is for machine {payload.get('machine')}, this computer is {machine}")
    if payload.get("expires"):
        if (today or dt.date.today()) > dt.date.fromisoformat(payload["expires"]):
            raise LicenseError(f"license expired on {payload['expires']}")
    return payload


def activate(token: str) -> dict:
    payload = verify(token)
    p = store_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps({"token": token.strip(), "activated": dt.datetime.now().isoformat(timespec="seconds")}), encoding="utf-8")
    return payload


def status() -> dict:
    info: dict = {"enforced": enforced(), "machine": machine_id(), "valid": False}
    p = store_path()
    if not p.is_file():
        info["reason"] = "no license activated on this computer"
        return info
    try:
        token = json.loads(p.read_text(encoding="utf-8"))["token"]
        payload = verify(token)
        info.update(valid=True, licensee=payload.get("licensee"), expires=payload.get("expires"), features=payload.get("features"))
    except (LicenseError, KeyError, json.JSONDecodeError) as exc:
        info["reason"] = str(exc)
    return info


def require_license() -> None:
    """Called by the CLI for every command except `license`; a no-op when enforcement is off."""
    if not enforced():
        return
    s = status()
    if not s["valid"]:
        raise LicenseError(f"{s.get('reason', 'no valid license')} - machine id {s['machine']}; run `kdp license activate <key>`")
